"""Builds AbilityDraft/AbilityPool.g.cs from the user's own Deadlock install.

Inputs (never shipped): decompiled scripts/heroes.vdata + scripts/abilities.vdata (see tools/dump-vdata.ps1)
and the loose localization files in game/citadel/resource/localization.
Usage: python gen_pool.py <dump dir> <Deadlock dir> <out .cs>
"""
import io, re, sys

dump, game, out = sys.argv[1:4]
heroes = open(f"{dump}/heroes.vdata", encoding="utf-8").read()
abil = open(f"{dump}/abilities.vdata", encoding="utf-8").read()


def loc(folder, lang):
    path = f"{game}/game/citadel/resource/localization/{folder}/{folder}_{lang}.txt"
    try:
        raw = open(path, "rb").read()
    except OSError:
        return {}
    text = raw.decode("utf-16") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8-sig", "replace")
    return {k.lower(): v for k, v in re.findall(r'^\s*"([^"]+)"\s+"((?:[^"\\]|\\.)*)"', text, re.M)}


names = {lang: {**loc("citadel_gc_hero_names", lang), **loc("citadel_gc", lang), **loc("citadel_heroes", lang)}
         for lang in ("english", "russian")}


def blocks(text):
    parts = re.split(r"\n\t(?=[A-Za-z_0-9]+ = \n\t\{)", text)
    return {m.group(1): p for p in parts if (m := re.match(r"([A-Za-z_0-9]+) = ", p))}


def field(block, key):
    m = re.search(r"\n\t\t" + key + r' = (?:panorama:)?"?([^"\n]+)"?', block)
    return m.group(1) if m else ""


def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# Still marked "in development" in the game data, yet on the hero select screen and playable.
PLAYABLE_ANYWAY = {"hero_baba"}
# Not pickable: only their abilities go into the pool.
UNRELEASED = set()
ab = blocks(abil)
rows = []
skipped = []
icons = {}
for hero, b in blocks(heroes).items():
    if not hero.startswith("hero_") or hero in ("hero_base", "hero_targetdummy", "hero_genericperson"):
        continue
    # Heroes still marked "in development" are left out, except the ones named in the two lists above.
    if field(b, "m_bDisabled") == "true" or field(b, "m_bInDevelopment") == "true" and hero not in PLAYABLE_ANYWAY | UNRELEASED:
        continue
    sig = [m.group(1) if (m := re.search(r'ESlot_Signature_%d = "([^"]+)"' % i, b)) else None for i in range(1, 5)]
    if None in sig:
        skipped.append(hero)
        continue
    icons[hero] = field(b, "m_strIconImageSmall")
    en = names["english"].get(hero + ":n", hero[5:].title())
    ru = re.sub(r"^#\|\w\|#", "", names["russian"].get(hero + ":n", en))
    for i, a in enumerate(sig):
        blk = ab.get(a, "")
        ult = "Ultimate" in field(blk, "m_eAbilityType")
        rows.append((hero, en, ru, i + 1, a, names["english"].get(a, a), names["russian"].get(a, names["english"].get(a, a)),
                     ult, field(blk, "m_strAbilityImage")))

with io.open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// <auto-generated> tools/gen_pool.py - names and ids only, read from the local Deadlock install. </auto-generated>\n")
    f.write("namespace AbilityDraft;\n\npublic static partial class AbilityPool\n{\n    public static readonly AbilityDef[] All =\n    [\n")
    for r in rows:
        f.write("        new(%s, %s, %s, %d, %s, %s, %s, %s, %s),\n" % (
            cs(r[0]), cs(r[1]), cs(r[2]), r[3], cs(r[4]), cs(r[5]), cs(r[6]), "true" if r[7] else "false", cs(r[8])))
    f.write("    ];\n\n    // Heroes that cannot be picked yet; only their abilities are in the pool.\n")
    f.write("    public static readonly string[] Unreleased = [%s];\n\n" % ", ".join(cs(h) for h in sorted(UNRELEASED)))
    f.write("    // The small portrait of each hero, for the vote panel.\n    public static readonly Dictionary<string, string> HeroIcons = new()\n    {\n")
    for hero in sorted(icons):
        if icons[hero]:
            f.write("        [%s] = %s,\n" % (cs(hero), cs(icons[hero])))
    f.write("    };\n\n")
    # An ability may bring others with it (its second stage, an alternate fire, a weapon). The engine creates them
    # with the ability but does not take them away when the ability is removed by hand.
    f.write("    // Abilities that come with another one (second stages, alternate fire), by the ability that brings them.\n")
    f.write("    public static readonly Dictionary<string, string[]> Dependents = new()\n    {\n")
    for name, blk in sorted(ab.items()):
        m = re.search(r"\n\t\tm_mapDependentAbilities = \n\t\t\{\n((?:\t\t\t[^\n]*\n)*)\t\t\}", blk)
        deps = [d for d in re.findall(r"^\t\t\t([A-Za-z_0-9]+) = ", m.group(1), re.M) if d in ab] if m else []
        if deps:
            f.write("        [%s] = [%s],\n" % (cs(name), ", ".join(cs(d) for d in deps)))
    f.write("    };\n\n")
    passive = sorted({r[4] for r in rows if "ACTIVATION_PASSIVE" in field(ab.get(r[4], ""), "m_eAbilityActivation")})
    f.write("    // Pool abilities that are never pressed: the Shuffle format swaps them on a clock instead.\n")
    f.write("    public static readonly HashSet<string> Passives =\n    [\n")
    for name in passive:
        f.write("        %s,\n" % cs(name))
    f.write("    ];\n\n")
    weapon = sorted(n for n, blk in ab.items() if n.startswith("upgrade_") and field(blk, "m_eItemSlotType") == "EItemSlotType_WeaponMod")
    f.write("    // Shop items of the weapon category.\n    public static readonly string[] WeaponItems =\n    [\n")
    for name in weapon:
        f.write("        %s,\n" % cs(name))
    f.write("    ];\n}\n")
print(f"{len(rows)} abilities from {len(rows)//4} heroes; skipped (no kit): {skipped}")
